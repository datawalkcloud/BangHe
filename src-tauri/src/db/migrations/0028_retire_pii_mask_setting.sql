--
-- 这枚键从来没生效过。0006 把它连同 `retention_sample_days` 一起补进 `app_setting`
-- （那一行注释写的是"界面显示身份证号中间打码（与 pii_encrypt_enabled 的存储加密是两回事"，
-- 03 §9.3.1 同一句），参数目录也照这个口径给了 hint（`src/lib/settings-catalog.ts`：
-- "只管屏幕上显不显示全号"）。但**唯一读它的是备份页那张"留存合规自查"卡片**：
-- `system.rs::collect_backup_status` 把它原样取出，`SystemPage` 拿它显示一行结论——
-- 真正画身份证号的那 36 处（18 个文件）全走 `src/lib/format.ts::maskIdCard`，
-- 而 `maskIdCard` 一个字都不读这枚键。
--
-- 于是一台把开关拨到"关闭"的站点机上，屏幕与导出里仍然是掩码，而自查卡会告诉站长
-- "已关闭：身份证明文会出现在屏幕与导出里"。**这张卡在替站长对迎检的人签字**，
-- 签的还是与事实相反的那一句。合规自查卡片的整张表都是"数值取自真库参数与文件"，
-- 留一个不驱动任何代码路径的键在里面，比少一项自查更贵。
--
-- 这一轮同时改掉的是证号能不能看全号（04 §3.3）：界面上默认仍是掩码，但每一格点开
-- 走 `orders::party_id_card` 取回全号并逐次落一条 `pii.read`；台账导出的证号列出全号，
-- 并记一条含"导出含身份证号明文"的留痕；打印票面与小票保持掩码。这三件事都不再是
-- 站长可配项，而是代码写死的口径——**能配置的只剩"有没有人在翻"**，那一格由
-- `system.rs::count_id_card_reads` 从 `audit_log` 真查近 30 天，取代本键在自查卡上的位置。
--
-- 历史脚本（0006 那一行）一字不改：迁移按已应用哈希校验，改历史即校验失败、
-- 装机版直接拒启。这里只在末尾 DELETE，把这行从存量库里请出去。
--
-- 键集要与 03 §9.3.1 逐字相等，否则 schema_contract::seed_baseline_matches_design_doc
-- 会红；前端目录里若还留着这个键，
-- masters_contract::every_key_the_frontend_catalog_renders_exists_in_the_library 也会红；
-- `system-native.ts` / `SystemPage` 里若还引用 `pii_mask_id_card`，`npx tsc` 会拦下来。
--
-- 不动的东西，列在这里免得下一个人顺手做：
--  · `pii_encrypt_enabled` **留着**——它同样是占位（字段级 AES-GCM 基建还没写，
--    03 §4 与 §9.15 已公开承认 `id_card_no_enc` 存的是明文过渡态），但它至少没在自查卡上
--    冒充一条已生效的合规措施。退役它要连着 §4 那一整段口径走，是加密基建那一轮的事；
--  · `reprint_need_auth` 也留着：它与本键是同一批（0006）里另一枚"拨了不生效"的键
--    （补打的站长授权链路已随 2026-09 那轮改造移除），但它牵动 05 §5 与补打话术一整片，
--    塞进这一轮会让改动面失控。另开一轮处理；
--  · 不改 `party` 任何一列（证号仍存明文 BLOB，本轮没让存储变得更安全，也没让它更不安全）；
--  · 不动 `audit_log`：`pii.read` 这个动作码 0001 就写在列注释里、也有中文话术，
