-- 0026_retire_doc_no_prefix.sql —— 退役 `doc_no_prefix_BD/ZJ/JS/FK/CK` 五枚参数键
--
-- 现场账（两次，都是同一件事）：磅房那台开着中文输入法的装机上，票面印
-- `BH1:BD01202610000053`，键盘模拟扫码枪打进来是 `BH：BD1202610000053`——`B`、`H` 落进
-- 拼音合成串，紧跟的 `1` 被当成候选项序号键吃掉、冒号折成全角；另一台更狠，整串只剩
-- `D01202610000069`（`src/lib/ticket-code.ts` 头注、`src/hooks/useScannerCapture.ts`
-- 的实测记录、04 §5.6）。当时补的三道（解析侧只放宽版本位、捕获侧看到合成事件就说破
-- "请切英文"、`ime.rs` 窗口聚焦时翻一次输入法开关）都救不回**已经被吞掉的数字**。
--
-- 字母是这件事的必要条件：一串纯数字没有任何东西可以开始拼拼音。所以这一轮把号与载荷
-- 一起数字化的根收掉（§3.5 / 02 §F1.4）：
--   · 业务单号 = `<站点码2><年4><月2><流水 seq_len>`，例 `01202610000053`；
--   · 票面码载荷 = `<版本位1><票种位1><单号>`，例 `1101202610000053`（磅单）/
--     `1301202610000053`（结算凭证）。票种码 1=磅单 2=质检 3=结算 4=付款 5=出库。
-- 种类必须留在载荷里：同一站点同一月里磅单与结算凭证各自从 1 号排起
-- （`seq_counter` 的键是 `<doc>:<站码>:<年月>`，与各单号的**前缀值**无关），纯数字化之后
-- 两种票必然出现同一串号，扫码口只拿号就把"来结算的"与"来付尾款的"混成一张——那是钱的事。
--
-- 五枚键从这里开始没有任何代码会读：`orders.rs::next_no` 走的是空前缀，
-- 参数目录（`src/lib/settings-catalog.ts`）同步删掉那四行展示项（`CK` 本来就没进目录，
-- 一直挂在设置页最后一组"库里新增、目录还没补"下面）。留着它们，就是让站长去改一个
-- 改了不生效的框——这正是 0006 那轮对键要根治的漂移。
--
-- 历史脚本（0002 的四枚、0020 的 `CK`）一字不改：迁移按已应用哈希校验，
-- 改历史即验校失败、装机版直接拒启。这里只在末尾 DELETE，把五行从存量库里请出去。
--
-- **`doc_no_prefix_YP` / `doc_no_prefix_LY` 不在退役之列**（0025 刚纳入统一取号）：
-- 样品号与留样号贴在样袋和留样瓶上，靠人肉眼认，从来不上扫码枪；`YP` / `LY` 就是
-- "这是样袋还是留样瓶"最快的那两个字。只有会被扫的号才欠字母这笔账。
--
-- 键集要与 03 §9.3.1 逐字相等，否则 schema_contract::seed_baseline_matches_design_doc
-- 会红；目录里若还留着这些键，
-- masters_contract::every_key_the_frontend_catalog_renders_exists_in_the_library 也会红。
--
-- 不动的东西，列在这里免得下一个人顺手做：
--  · 不改任何一列的类型与约束（`order_no` 等本来就是 TEXT，存数字串）；
--  · **不回灌历史单号**——`BD01202610000053` 照旧躺在库里，已发到农户手里的票照扫
--    （解析侧的 `BH1:` 那一轨永久只读兼容，票面码载荷跟着单号自己的形状走）；
--  · 不给 `seq_counter` 补账：计数器键从来不含前缀值，升级后新取的号接着当月流水往上排，
--    与历史号不会撞（同月内历史号已经占掉的那几个序号，计数器早已算过了）。
-- ============================================================================

DELETE FROM app_setting WHERE key IN (
  'doc_no_prefix_BD',
  'doc_no_prefix_ZJ',
  'doc_no_prefix_JS',
  'doc_no_prefix_FK',
  'doc_no_prefix_CK'
);
