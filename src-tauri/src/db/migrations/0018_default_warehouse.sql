-- ============================================================================
-- 0018_default_warehouse.sql —— 制单默认仓房（03 §9.3.1 参数基线；界面行为见 05 §4 制单面板）
--
-- 现场痛点：站里只有一处仓房时，去向那格本来没有选择题，磅员却每单都要展开下拉点一次；
-- 有多处仓房的站，粮通常固定进同一两间，也每单手选。改法：
--   · 启用仓房只有一处 → 制单草稿直接选中它（无需本参数，界面上也不给「按参数」的余地）；
--   · 有多处 → 认这里预设的 default_warehouse_id，制单时自动带出；
--   · 本参数留空（默认）→ 多仓站照旧「未定」，行为与升级前完全一致。
-- 自动带出只是初始值：磅员在草稿里手动改过仓房（含改回「未定」）后，这一单不再自动回填；
-- 预设的仓房后来被停用/删除，按未预设处理，绝不把单派进一间不存在的库房。
--
-- 只加一个参数键，不动表结构（与 0010/0012/0014/0016 同规）。值是仓房 id 的文本，
-- 空串＝未预设；存 string 不存 int，是为了让「没有默认」不必占用 0 这个魔法数。
-- 只 INSERT OR IGNORE，站长已手动改过的值升级不覆盖。键集要与 03 §9.3.1 逐字相等，
-- 否则 schema_contract::seed_baseline_matches_design_doc 会红；
-- 目录里这一行若缺，masters_contract::every_key_the_frontend_catalog_renders_exists_in_the_library 也会红。
-- ============================================================================

INSERT OR IGNORE INTO app_setting (key, value_json, value_type, description, updated_at) VALUES
  ('default_warehouse_id', '""', 'string', '制单默认仓房：启用仓房只有一处时制单自动选它（与本参数无关）；有多处时新磅单的「入仓去向」自动带出这里预设的仓房，仍可当场改。留空＝多仓站不预设；预设仓房停用后按未预设处理', strftime('%Y-%m-%dT%H:%M:%f','now','localtime') || '+08:00');
