-- 0012_reader_prompt_voice.sql —— 读卡弹窗提示语音（docs/design/05 篇 §6.5）
--
-- 现场痛点：读卡器装在窗口外，弹窗只在磅员屏幕上，农户与司机看不见那行小字，
-- 每单都得磅员探头出去喊一次"把身份证放上去"。改法是让弹窗自己开口：
-- 身份证监听弹窗（CardScanDialog）、制单绑卡弹窗（CardBindDialog）、流转卡登记弹窗
-- （IcScanDialog）弹出的那一刻，本机扬声器念一句"请将……放在读卡器感应区"。
--
-- 发声走 WebView2 的平台语音合成（Windows 自带中文语音包），不联网、不引第三方 TTS、
-- 不加音频资源，与 07 篇那条「功放 + 音柱 + 片段包」的喊话链路是两条独立通路：
-- 这里只管弹窗所在这一台机器的近场提示，不进车间喇叭、不参与 07 §3 的通道仲裁。
-- 本机没装中文语音包时降级成一声提示音，并把原因上屏说清（07 §7「不允许静默失败」同一条）。
--
-- 只加一个参数键，不动表结构。与 0006/0008/0009/0010 同规：只 INSERT OR IGNORE，
-- 站长已手动改过的值升级不覆盖。键集要与 03 §9.3.1 逐字相等，
-- 否则 schema_contract::seed_baseline_matches_design_doc 会红。
-- ============================================================================

