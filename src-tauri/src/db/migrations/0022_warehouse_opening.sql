-- ============================================================================
-- 0022_warehouse_opening.sql —— 仓房期初建账（03 §9.9 仓房 / §9.23 库存流水）
--
-- 站长建仓房时手里通常已经有数：这间库房上还压着 1200 吨玉米（保管账实存）。没有「期初」
-- 这一格，库存账就从建库那天起算，结存、出库可用量、剩余容量全部偏低——出库那一路会把
-- 仓里真实存在的粮判成无货（0021 起 available_01kg 只认 stock_movement）。
--
-- 落点刻意选在库存流水，而不是给 warehouse 表加一个孤零零的期初列：0021 之后
-- `stock_movement` 是库存账的唯一账本（结存 = Σ入 − Σ出），期初另起一列就会出现两套
-- 「仓里有多少粮」，两边迟早对不上，而那正是最难归因的一类错账。
--
-- 为什么是 kind='in' + is_opening 标记，不新增 kind 值域：
--   · 结存、按仓房聚合、带符号流水（stock.rs 的 MOVE_WH 与 signed_01kg 都以 kind='in'
--     为正向）三处口径立刻自动吃进期初，一行 SQL 都不用改；'adjust' 在那套口径里是
--     从 from_warehouse 扣的负向盘亏方向，拿它记期初会把账算反。
--   · 扩 CHECK 值域要重建 stock_movement（SQLite 不能 ALTER 约束），而这张表正被出库
--     那一路频繁写入，重建的风险不值当。
--   · 判据要显式成列，不能靠「order_id 与 outbound_id 都为空的 in 行」反推：将来盘盈、
--     手工补录走的也是无来源的 in 行，靠形状认亲迟早认错。
--
-- 一仓一笔：下面的部分唯一索引逼住「同一仓房最多一条期初行」。期初是**基线**不是业务
-- 事件，改错了就 UPDATE 那一行（品种也跟着改），并在 audit_log 记前后值，而不是像出库
-- 红冲那样补一条对称流水——基线越纠错越多笔，档案页就没人看得懂「这仓 originally 装了多少」。
--
-- 只加列与索引，不动存量数据：老仓房没有期初行，读出来就是 NULL（＝从没申报过），
-- 不回填成 0——0 是一句「空仓起账」的明确表态，把没填演成填了是造出来的假数。
-- ============================================================================

ALTER TABLE stock_movement ADD COLUMN is_opening INTEGER NOT NULL DEFAULT 0;

CREATE UNIQUE INDEX IF NOT EXISTS uk_stock_opening
    ON stock_movement(to_warehouse_id)
    WHERE is_opening = 1;
