-- 0032_retire_scale_align_settings.sql —— 退役 `scale_division_01kg` / `weight_rounding_mode`
--
-- 这一轮把 `weigh_record.aligned_weight_01kg` 真正接上分度取整（04 §2.4 第 4 点
-- 「存原始值 + 取整值」欠的那一步）。接的时候必须回答"按哪一处的分度值算"，而仓库里
-- 同时躺着两处答案：
--
--  ① 这台磅的帧模板 `align` 段（`device_config.config_json`，04 §2.3）——读线程拿它
--     算 `ScaleEvent.aligned_01kg`，也就是面板上定格给人看的那个数；
--  ② 站点参数这两枚键（0002 建库时就写进基线，03 §3.1 第 5 条）——只有
--     `WorkstationPage` 读一次，喂给称重区标题那行「分度 10 kg · COM3」的字。
--
-- 于是「分度值」有两处可配，而**只有一处生效**：设备中心那台真磅的串口是照 ① 跑的，
-- 屏幕上那行字是照 ② 写的。站长把 ② 改成 5 kg，面板数字、判稳容差、库里那一列一个都
-- 不会变——这一格是在替不存在的事签字。
--
-- 为什么退役的是 ②、留下的是 ①：分度值是**设备属性**，不是站点属性。台账里 1 号磅
-- 10 kg、2 号磅 20 kg 是合法现场（一条秤台短、一条长，法制分度本来不同），而 ② 只有
-- 一个数，表达不了这件事；`weigh_record.device_id` 已经记了"这一捕是哪台磅称的"，
-- 取整依据却来自一个与设备无关的全局键，本身就对不上。设备中心也早就写明
-- 「窗口、容差与分度写在这台磅的帧模板里，站点参数不参与判稳」。
--
-- 顺带一条对不上的：② 的 `weight_rounding_mode` 值域是 `floor` / `half_up` / `nearest_div`，
-- 而 `scale.rs::Align::apply` 认的是 `floor_div` / `ceil_div` / `nearest_div` / `none`。
-- 目录里那个「向下取整」选项 `floor` 落进 `apply` 的 `_` 分支，会被当成"就近分度"执行——
-- 选了向下、实际按四舍五入算。两处的词表从来没对齐过，因为压根没有代码把 ② 喂给 `apply`。
--
-- 这一轮同时改掉的是称重区标题那一行：分度改读后端随帧下发的 `division_01kg`
-- （`src/store/device.ts` 早就存着，是 ① 的真值），没有真机帧时那一格不显示数字——
-- 与设备中心「界面不会凭空造读数」是同一条规矩。台账里没有启用的磅时
-- `scale.rs::capture_align` 回 `Align::none()`，整量化 = 读数：没有设备就没有分度，
-- 绝不拿文档默认的 10 kg 去改动磅员亲手敲进去的数。
--
-- 历史脚本（0002 那两行）一字不改：迁移按已应用哈希校验，改历史即校验失败、
-- 装机版直接拒启。这里只在末尾 DELETE，把两行从存量库里请出去。
--
-- 键集要与 03 §9.3.1 逐字相等，否则 schema_contract::seed_baseline_matches_design_doc
-- 会红；前端目录里若还留着这两个键，
-- masters_contract::every_key_the_frontend_catalog_renders_exists_in_the_library 也会红；
-- `WorkstationPage.tsx` 里若还 `useSetting("scale_division_01kg")`，那一格会继续显示
-- 一个库里已经不存在的数——`useSetting` 抢跑期回 0，`|| 100` 会把它兜成"分度 10 kg"，
-- tsc 拦不住，只有 `scripts/scale-align/check.ts` 的 C 段拦得住。
--
-- 不动的东西，列在这里免得下一个人顺手做：
--  · `weigh_record` 一列不改、不加索引：`aligned_weight_01kg` 0001 就建好了，
--    注释写的就是"按分度值取整后的值"，这一轮只是开始往里写对得上的数；
--  · **不回刷历史行**：库里已有的行是"捕获当时没取整"留下的，`weight_01kg` 与
--    `raw_frame` 都还在，真要按今天的分度重算随时可算。但历史磅单已经打印、
--    已经结算，轨迹表上"整量化"那一栏事后变数，等于改一张已经递出去的票；
--    迎检要的是"当时记了什么"，不是"今天重算出来什么"。要补这一段得单独拍板；
--  · 单头 `gross_weight_01kg` / `net_weight_01kg` 与结算金额**一律照旧吃原始捕获值**：
--    整量化这一轮只是轨迹里的法定读数留证，没有管到钱上（毛 564.3 − 皮 236.7 仍按
--    327.6 kg 结算，不按 560−240=320 kg）。改这一条会真实改变结算金额与历史口径，
--    是另一轮的事；
--  · 帧模板 `align` 段的编辑入口照旧（设备中心「编辑」表单不含它，要改走
--    配置导出 → 改 → 导入），本轮不新开表单。
-- ============================================================================

DELETE FROM app_setting WHERE key IN ('scale_division_01kg', 'weight_rounding_mode');
