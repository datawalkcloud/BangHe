-- ============================================================================
-- 0031_raise_attachment_max_kb.sql —— 抓拍图上限 500 KB → 2048 KB
--
-- 现场那台海康（`hikvision_isapi`，主码流 2560×1440）出的抓拍图实测 512 KB，
-- 设备中心因此挂红：「抓拍图有 512 KB，超过上限 500 KB：本轮不做缩放压缩，
-- 请到摄像机侧调低主码流分辨率与质量」，连续 5 次后被 `camera.rs::note_fail`
-- 压成"离线"，磅单从此静默无抓拍。
--
-- 根因不是相机配错，是**一枚按"会先压缩"来定的上限，配在了一条不压缩的代码路上**。
-- 04 §4.2 写的处理链路是「`image` crate 解码 → 长边 1600 px → JPEG 质量 80 →
-- 若 > `attachment_max_kb` 逐级降质」，500 这个数就是照那条链路定的——压缩之后
-- 落库的图本来就该远小于 500 KB。但全仓没有 JPEG 解码依赖（`Cargo.toml` 只有
-- `jpeg-encoder` 编码与 `openh264` 解 H.264，`image` 一处都没有），实现里
-- `camera.rs::exchange` 在 HTTP 头 `Content-Length` 阶段就拒收、`check_jpeg` 再拒一次。
-- 于是"上限"退化成"闸门"：主码流摄像机 500–900 KB 的正常出图，一张都进不来。
--
-- 本机 USB 摄像头为什么从来没撞过这道门：它的取帧发生在**前端 canvas**
-- （04 §4.2.1 方案 D，长边 ≤1600、质量 0.85 之后才回传），压缩那一层在前端已经做完了。
-- 缺的只有 IP 这一路。
--
-- 这一轮只做抬数，不补压缩链路：抬数是现场当天改一个参数就能生效的一步，
-- 补压缩要新引一个 JPEG 解码依赖并重排抓拍预算，是另一轮的事。
-- 04 §4.2 那一行同步改成与代码一致（写清"本轮不解码不缩放"与代价），
-- 免得下一个人照文档以为压缩已经存在。
--
-- 抬到 2048 的理由与代价，一次写清：
--  · 2048 KB 与手工上传附件的 4 MB 上限（`attachment.rs::MAX_IMAGE_BYTES`）同量级、
--    且更低。原来那两个数互相打脸：磅员手挑一张 3 MB 的照片系统收，相机自动出的
--    512 KB 反而拒。
--  · 上限不是占用。落库大小由相机出图决定，抬上限只是让 512–900 KB 这一档
--    从"整张丢弃"变成"照原样入库"，磁盘增量按出图大小算、不按上限算，
--    量级是 +30%~80% 而不是 4 倍。10 年留存（`attachment_keep_days=3650`）的
--    盘位预算仍要按每单最多 3 台 × 毛/皮 2 次重算，那一格记在 04 §4.2。
--  · `max_snapshot_bytes` 的合法区间 32..=20480 不变，2048 落在区间内；
--    站点仍可自己往下调（现场盘紧就调回 1024）。
--
-- 幂等口径：值那一改**只动仍是 500 的行**，站点自己配过的数一律不覆盖；
-- 文案那一改无条件，因为它与数值无关（"压缩上限"这个词对任何值都是假的）。
-- 历史脚本 0002 那一行一字不改：迁移按已应用哈希校验，改历史即校验失败、装机版拒启。
--
-- 同批改动的落点（缺一处就会留下第二个口径）：
--  · `camera.rs::DEFAULT_MAX_KB` 500 → 2048 —— 缺键兜底必须与参数默认同数；
--  · `camera.rs` 两处拒收话术 —— 上限来源要指到「基础档案 › 站点参数」那一格，
--    不能只让人去拧摄像机；
--  · `src/lib/settings-catalog.ts` 的 label 与 hint —— 同上，"压缩上限"改准，
--    并把"这一格现在管的是什么"写进提示；
--  · 03 §9.3.1 与 04 §4.2 文档口径。
-- 键集不变，`schema_contract::seed_baseline_matches_design_doc` 只比键名不比值，不受影响。
--
-- 【同日后续】上面"这一轮只做抬数、不补压缩"说的是本脚本落地那一刻的事实；
-- 同一批改动里 04 §4.2 那条压缩链路已经补上（`camera.rs::fit_to_budget`：
-- `jpeg-decoder` 解码 → 面积平均缩到长边 1600 → `jpeg-encoder` 逐级降质）。
-- 所以这一枚参数从"拒收闸门"变回了它的名字一直承诺的东西——**压缩的目标线**：
-- 未超限的图原样入库，超限的图被压进来，压到最小档仍超限才降级。
-- 抬到 2048 这件事本身仍然成立且必要：主码流出图 500–900 KB 是常态，
-- 让它们统统走一遍有损重编去挤 500 KB，等于把凭证质量白降一档。
-- 本脚本的 SQL 语句一字未改（只有这段注释是后加的），已应用过它的机器不会校验和漂移。
-- ============================================================================

UPDATE app_setting
   SET value_json = '2048',
       updated_at = strftime('%Y-%m-%dT%H:%M:%f','now','localtime') || '+08:00'
 WHERE key = 'attachment_max_kb'
   AND value_json = '500';

UPDATE app_setting
   SET description = '抓拍图落库上限（KB）：未超限的原图一个字节不动；超限才解码、缩到长边 1600、逐级降质压进来（04 §4.2）。压到最小档仍超限才按无抓拍降级'
 WHERE key = 'attachment_max_kb';
