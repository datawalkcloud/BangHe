-- ============================================================================
-- 0034_package_deduct_ratio.sql —— 默认扣包支持按比例（issue #3）
--
-- `default_package_deduct_01kg` 只会记"每车固定几公斤"。按袋计皮的站点够用，
-- 但另一类站点包皮随量走：一车 30 吨和半车 5 吨扣同一个数，半车那张就被多扣。
-- 以前只能自己把比例换算成公斤填进档案，于是半车、整车各要各的数，档案里那个
-- 固定值就成了只对满车成立的假默认。
--
-- 加一列可空的 0.01% 定点比例，与同表其它基准（`std_moisture_001pct` 那一族）
-- 同一口径、同一控件。两列的取舍只判一次：**比例非空且 > 0 时按比例，否则按固定公斤**
-- （`src/lib/settle-defaults.ts::varietyPackageDeduct01kg`）。
-- 刻意不再加一枚"模式"枚举列：现场要的就是"要么填公斤、要么填百分比"，
-- 多一个开关等于多一种自相矛盾的行（模式是比例、比例却是空）。
--
-- 可空且默认 NULL：升级后老行行为逐字不变——NULL 走固定公斤那一支，值还是原来那个。
--
-- **不动 `weigh_order.package_deduct_01kg`**：磅单上落的始终是折算完的公斤数。
-- 结算校验（`orders.rs::settle` 的"扣重合计不得超净重"）、票面、对账全部只看那一列，
-- 比例只是档案提供默认值的一种来源，不进结算公式、不进票面。
-- ============================================================================

ALTER TABLE grain_variety ADD COLUMN default_package_deduct_001pct INTEGER;
