-- 0023_scan_test_input.sql —— 工作台测试扫码框（05 §4 工作台底部；02 §F1.4 扫票那一步）
--
-- 现场痛点：结算与挂账核销都从"扫一下票面码"起步（`useScannerCapture` 常驻听键盘），
-- 可是三类场合手上没有枪：装完机还没接枪、枪坏了排在配件路上、以及拿浏览器演示给
-- 粮站看流程。这时窗口上那一框永远弹不出来，验收与培训都卡在这一步。
--
-- 改法：允许在工作台页面底部挂一个「测试扫码框」，把一串 `BH1:` 载荷贴进去按回车，
-- 走的是与扫码枪**同一个回调**（`handleScan`）——同一份前缀分流、同一套闸门与话术、
-- 同样弹结算框或补付框。刻意不重做一套"测试版结算入口"：另开一条路的测试框，
-- 测出来的结论对不上真枪那条路，比没有测试框更坏。
--
-- 它替代的只是"枪把字符敲进电脑"这一段，替代不了硬件本身：按键间隔 80ms 的枪判、
-- 「光标在输入框里时不抢键」这两条捕获规则仍然只有真枪能验（05 §5）。
--
-- 只加一个参数键，不动表结构（与 0010/0012/0014/0016/0018 同规）。
-- 默认 false——这是排障与演示用的辅助件，不该在交出去的生产机上自己冒出来；
-- 关掉那一框整条消失，页面与升级前逐字一致。
-- 只 INSERT OR IGNORE，站长已手动改过的值升级不覆盖。键集要与 03 §9.3.1 逐字相等，
-- 否则 schema_contract::seed_baseline_matches_design_doc 会红；
-- 目录里这一行若缺，masters_contract::every_key_the_frontend_catalog_renders_exists_in_the_library 也会红。
-- ============================================================================

